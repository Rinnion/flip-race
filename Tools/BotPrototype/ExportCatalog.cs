    static int checks;
    static void Need(bool yes,string why){checks++;if(!yes)throw new Exception(why);}
    static void Reject(Action action){bool rejected=false;try{action();}catch(ArgumentException){rejected=true;}Need(rejected,"invalid selection must reject");}
    static void Verify(List<Group> groups)
    {
        Need(BotPlanCatalog.FirstReportSha256==Hash(File.ReadAllBytes(First)),"first report provenance");Need(BotPlanCatalog.ComplexReportSha256==Hash(File.ReadAllBytes(Complex)),"complex report provenance");
        var actual=new List<(string Id,double[] Distances)>();
        foreach(var group in groups)
        {
            FlightSettings flight=group.Profile=="Jump"?FlightPresets.Chosen:FlightPresets.FastFlip;BotDifficulty difficulty=Enum.Parse<BotDifficulty>(group.Level);
            Need(BotPlanCatalog.IsSupported(group.Track,flight),"supported");Need(BotPlanCatalog.Count(group.Track,flight,difficulty)==group.Plans.Length,"plan count");Need(BotPlanCatalog.GoalCount(group.Track,flight)==group.Goals.Length,"goal count");Need(BotPlanCatalog.GoalIds(group.Track,flight).SequenceEqual(group.Goals),"goal IDs");Need(BotPlanCatalog.CatalogHash(group.Track,flight)==group.CatalogHash,"catalog hash");
            var goals=BotPlanCatalog.GoalIds(group.Track,flight);goals[0]="modified";Need(BotPlanCatalog.GoalIds(group.Track,flight)[0]==group.Goals[0],"defensive goal copy");
            for(int index=0;index<group.Plans.Length;index++)
            {
                var expected=group.Plans[index];var plan=BotPlanCatalog.Select(group.Track,flight,difficulty,index);var again=BotPlanCatalog.Select(group.Track,flight,difficulty,index);
                Need(plan.Id==expected.Id&&plan.Id==again.Id&&plan.TrackId==group.Track&&plan.ProfileId==(group.Profile=="Jump"?"Chosen":"FastFlip")&&plan.Seed==index&&plan.Difficulty==difficulty&&plan.PlanIndex==index,"plan metadata");Need(plan.InputCount==expected.Distances.Length,"input count");
                for(int i=0;i<plan.InputCount;i++){Need(BitConverter.DoubleToInt64Bits(plan.GetDistance(i))==BitConverter.DoubleToInt64Bits(expected.Distances[i]),"roundtrip distance "+plan.Id+" edge"+i);Need(BitConverter.DoubleToInt64Bits(plan.Distances[i])==BitConverter.DoubleToInt64Bits(expected.Distances[i]),"copy distance");}
                actual.Add((plan.Id,plan.Distances));var change=plan.Distances;if(change.Length>0){change[0]=-1;Need(plan.GetDistance(0)==expected.Distances[0]&&BotPlanCatalog.Select(group.Track,flight,difficulty,index).GetDistance(0)==expected.Distances[0],"defensive plan copies");}
                Need(BotPlanCatalog.Select(group.Track,flight,difficulty,index+1).Id!=plan.Id,"repeat new plan");Need(BotPlanCatalog.Select(group.Track,flight,difficulty,index+group.Plans.Length).Id==plan.Id,"modulo selection");
            }
            Need(BotPlanCatalog.Select(group.Track,flight,difficulty,-1).Id==group.Plans.Last().Id,"negative seed modulo");
            foreach(int seed in new[]{int.MinValue,int.MaxValue})Need(BotPlanCatalog.Select(group.Track,flight,difficulty,seed).Seed==seed,"extreme seed");
            var cloned=new FlightSettings(flight.FirstAction,flight.Law,flight.AirRepeats,flight.GravityAcceleration,flight.FlipImpulse,flight.JumpImpulse,flight.LinearSpeed,flight.LinearJumpHeight);Need(BotPlanCatalog.IsSupported(group.Track,cloned),"exact preset clone");
