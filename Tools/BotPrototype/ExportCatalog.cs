    static string Quote(string s)=>JsonSerializer.Serialize(s);
    static List<Group> Read()
    {
        var groups=new List<Group>();using(var doc=JsonDocument.Parse(File.ReadAllText(First)))
        {
            if(doc.RootElement.GetProperty("status").GetString()!="PASS")throw new Exception("First report not PASS");
            foreach(var pair in doc.RootElement.GetProperty("evidence").EnumerateArray())foreach(var level in pair.GetProperty("libraries").EnumerateArray())groups.Add(new Group{Track=pair.GetProperty("track").GetString(),Profile=pair.GetProperty("profile").GetString(),Level=level.GetProperty("level").GetString(),CatalogHash=pair.GetProperty("catalogHash").GetString(),Goals=pair.GetProperty("catalog").EnumerateArray().Select(x=>x.GetString()).ToArray(),Plans=level.GetProperty("plans").EnumerateArray().Select(p=>new Entry{Id=p.GetProperty("Id").GetString(),Distances=p.GetProperty("Distances").EnumerateArray().Select(x=>x.GetDouble()).ToArray()}).ToArray()});
        }
        using(var doc=JsonDocument.Parse(File.ReadAllText(Complex)))
        {
            if(doc.RootElement.GetProperty("Result").GetString()!="PASS")throw new Exception("Complex report not PASS");
            foreach(var pair in doc.RootElement.GetProperty("Evidence").EnumerateArray())foreach(var level in pair.GetProperty("Levels").EnumerateArray())groups.Add(new Group{Track=pair.GetProperty("Track").GetString(),Profile=pair.GetProperty("Profile").GetString(),Level=level.GetProperty("Level").GetString(),CatalogHash=pair.GetProperty("CatalogHash").GetString(),Goals=pair.GetProperty("Catalog").EnumerateArray().Select(x=>x.GetString()).ToArray(),Plans=level.GetProperty("Plans").EnumerateArray().Select(p=>new Entry{Id=p.GetProperty("Id").GetString(),Distances=p.GetProperty("Distances").EnumerateArray().Select(x=>x.GetDouble()).ToArray()}).ToArray()});
        }
        if(groups.Count!=50||groups.Select(g=>g.Track+"/"+g.Profile).Distinct().Count()!=10||groups.Sum(g=>g.Plans.Length)!=343||groups.Any(g=>g.Plans.Length<2))throw new Exception("Source coverage/count mismatch");
        foreach(var group in groups)
        {
            if(Hash(Encoding.UTF8.GetBytes(string.Join("\n",group.Goals)))!=group.CatalogHash)throw new Exception("Catalog hash mismatch "+group.Track);
            foreach(var plan in group.Plans)for(int i=0;i<plan.Distances.Length;i++)if(!double.IsFinite(plan.Distances[i])||plan.Distances[i]<0||(i>0&&plan.Distances[i]<plan.Distances[i-1]))throw new Exception("Invalid source tape "+plan.Id);
        }
        return groups;
    }
    static string Fingerprint(IEnumerable<(string Id,double[] Distances)> plans)
    {
        var text=new StringBuilder();foreach(var p in plans){text.Append(p.Id).Append('\n');foreach(double d in p.Distances)text.Append(BitConverter.DoubleToInt64Bits(d).ToString("X16",CultureInfo.InvariantCulture)).Append(',');text.Append('\n');}return Hash(Encoding.UTF8.GetBytes(text.ToString()));
    }
